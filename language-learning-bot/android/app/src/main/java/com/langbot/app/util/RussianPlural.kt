package com.langbot.app.util

/**
 * Согласование существительного с числом по-русски.
 *
 * Счётчики внизу карточки склеивались как "$n ошибок", и при единице на экране
 * выходило «1 ошибок». Заметил это снимок экрана из ScreenshotTest — чтением
 * кода такое не видно, строка выглядит совершенно обычно.
 *
 * Формы задаются в порядке: 1 ошибка, 2 ошибки, 5 ошибок.
 */
fun plural(n: Int, one: String, few: String, many: String): String {
    val abs = if (n < 0) -n else n
    val mod100 = abs % 100
    // 11–14 всегда берут форму «много»: одиннадцать ошибок, а не «ошибка».
    if (mod100 in 11..14) return many
    return when (abs % 10) {
        1 -> one
        2, 3, 4 -> few
        else -> many
    }
}

/** «1 ошибка», «2 ошибки», «5 ошибок». */
fun mistakes(n: Int): String = "$n " + plural(n, "ошибка", "ошибки", "ошибок")

/**
 * «1 правильный», «2 правильных», «5 правильных» — существительное («ответ»)
 * опущено, поэтому у 2–4 и 5+ форма совпадает.
 */
fun correct(n: Int): String = "$n " + plural(n, "правильный", "правильных", "правильных")
