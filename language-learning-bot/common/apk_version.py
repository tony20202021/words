"""
Версия Android-приложения — из самого APK, а не из common/version.py.

Зачем отдельно от version.py
----------------------------
version.py говорит, какая версия у ИСХОДНИКОВ. А раздаётся отдельный артефакт —
android/LangBot.apk, собранный когда-то раньше. Между «подняли версию» и
«пересобрали APK» всегда есть промежуток, и в нём эти два числа расходятся.

Чем расхождение кончается. Веб когда-то называл файл по version.py и отдавал
v3.0.72, внутри которого лежал 3.0.71. 09.10.2026 то же случилось с ботом и
страницей скачивания крупнее: ссылка обещала 4.11.0, а скачивался 4.6.5 —
версию подняли пять раз подряд, а копию APK в раздачу не положили ни разу.
Отдельного шага в сборке не было, он жил пунктом в документации.

Шаг теперь часть сборки (android/app/build.gradle кладёт APK сам), а это —
вторая опора: что бы ни лежало в LangBot.apk, названо оно будет своим именем.
"""

import re
import zipfile
from pathlib import Path


def apk_version(apk_path: Path) -> str:
    """
    versionName, прочитанный из самого APK; если не вышло — версия исходников.

    Двоичный AndroidManifest.xml хранит строки в UTF-16LE, и versionName
    переживает наивное декодирование — для этой задачи достаточно. Берём ответ,
    только если тройка цифр в манифесте ровно одна: две разные означали бы, что
    мы поймали что-то ещё, и тогда честнее вернуть версию исходников, чем
    назвать файл наугад.
    """
    try:
        with zipfile.ZipFile(apk_path) as z:
            manifest = z.read("AndroidManifest.xml").decode("utf-16-le", errors="ignore")
        found = sorted(set(re.findall(r"\d+\.\d+\.\d+", manifest)))
        if len(found) == 1:
            return found[0]
    except Exception:
        pass

    from common.version import __version__
    return __version__
