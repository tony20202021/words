"""
Имя машины, на которой всё крутится.

Зачем: владелец держит несколько серверов и спросил показывать это прямо в
приветствии бота — «а то я уже забываю где что».

Берётся у самой системы, а не из настройки: настройка переезжает вместе с
кодом и начинает врать на новой машине молча. Имя хоста соврать не может.
"""
import socket


def server_name() -> str:
    """Короткое имя машины: i-04, а не i-04.example.net."""
    try:
        return socket.gethostname().split(".")[0] or "?"
    except Exception:          # имя недоступно — лучше прочерк, чем падение
        return "?"
