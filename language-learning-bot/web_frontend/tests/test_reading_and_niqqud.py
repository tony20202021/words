"""Две новые вещи на карточке веба: примеры для чтения и переключение огласовки.

ПРИМЕРЫ ДЛЯ ЧТЕНИЯ — свой тип блока, не «extra». Таблицу однокоренных
переиспользовать нельзя: там на слово отведено 33% ширины, и предложение в
такую колонку не влезает. А сам шаблон фильтрует элементы по списку типов —
тип, которого в списке нет, молча не рисуется, и карточка выходит пустым
белым прямоугольником. Поэтому проверяется не «не упало», а что текст
предложения и перевод действительно есть в разметке.

ОГЛАСОВКА — владелец: «реальные тексты без огласовок, нужен промежуточный
этап, когда огласовка включается по простому нажатию». Обе формы приходят
в карточке, переключение клиентское: иначе оно не работало бы без сети.
"""
import pytest

from app.templating import templates

СТРОКИ_ЧТЕНИЯ = [
    {"marker": "1", "rank": 1, "foreign": "יש זמן", "ru": ""},
    {"marker": "", "rank": None, "foreign": "", "ru": "Время есть."},
    {"marker": "2", "rank": 2, "foreign": "זמן טוב", "ru": ""},
    {"marker": "", "rank": None, "foreign": "", "ru": "Хорошее время."},
]


def _карточка(**поверх):
    основа = {
        "meta": {"score_badge": {"variant": "secondary", "text": "новое"},
                 "word_number": 87, "result_history": [], "correct_count": 0,
                 "incorrect_count": 0, "words_for_today": 5},
        "content": [], "sounds": [], "buttons": [], "show_answer": True,
        "extra_groups": [],
    }
    основа.update(поверх)
    tpl = templates.env.get_template("partials/word_card.html")
    return tpl.render(card=основа, lang={"name_ru": "Иврит"}, language_id="l1")


@pytest.fixture(scope="module")
def с_чтением():
    return _карточка(extra_groups=[{"items": [
        {"type": "label", "text": "📖 Примеры для чтения:", "group": "reading"},
        {"type": "reading", "group": "reading", "rows": СТРОКИ_ЧТЕНИЯ},
    ]}])


def test_предложения_и_переводы_попадают_в_разметку(с_чтением):
    assert "יש זמן" in с_чтением and "זמן טוב" in с_чтением
    assert "Время есть." in с_чтением and "Хорошее время." in с_чтением
    assert "Примеры для чтения" in с_чтением


def test_предложение_и_перевод_в_разных_строках_таблицы(с_чтением):
    """Владелец просил перевод следующей строкой, а не рядом с текстом."""
    строка_с_текстом = с_чтением.index("יש זמן")
    строка_с_переводом = с_чтением.index("Время есть.")
    между = с_чтением[строка_с_текстом:строка_с_переводом]
    assert "</tr>" in между, "текст и перевод оказались в одной строке таблицы"


def test_иностранная_строка_идёт_справа_налево(с_чтением):
    """Без этого строка с ивритом прижималась бы влево вместе с номером."""
    кусок = с_чтением[с_чтением.index("יש זמן") - 200:с_чтением.index("יש זמן")]
    assert 'dir="rtl"' in кусок


@pytest.fixture(scope="module")
def с_огласовкой():
    return _карточка(content=[{"type": "foreign", "text": "זמן",
                               "text_simple": "זמן", "text_full": "זְמַן",
                               "simplified_first": True}],
                     big_word={"word": "זמן", "word_simple": "זמן",
                               "word_full": "זְמַן", "transcription": "zman"})


def test_обе_формы_лежат_в_разметке(с_огласовкой):
    """Переключение клиентское — значит вторая форма должна быть на странице."""
    assert 'data-simple="זמן"' in с_огласовкой
    assert 'data-full="זְמַן"' in с_огласовкой
    assert "toggleNiqqud" in с_огласовкой


def test_без_второй_формы_кнопки_нет():
    """Английское слово: кнопка, которая ничего не меняет, хуже её отсутствия."""
    вышло = _карточка(content=[{"type": "foreign", "text": "time"}])
    assert "time" in вышло
    assert "toggleNiqqud(this)" not in вышло


def test_совпадающие_формы_кнопки_не_дают():
    вышло = _карточка(content=[{"type": "foreign", "text": "מי",
                                "text_simple": "מי", "text_full": "מי"}])
    assert "toggleNiqqud(this)" not in вышло
