/*
 * Разбор словаря иврита по внешним источникам: сценарий многоагентного прогона.
 *
 * Как запускать
 * -------------
 *   Workflow({ scriptPath: '<этот файл>', args: { from: 201, to: 400, step: 50 } })
 *
 * Устройство
 * ----------
 * Диапазон рангов режется на партии по step слов. На каждую партию — проверяющий,
 * который смотрит ВСЕ поля всех слов партии против досье (dossier_1000.jsonl), и
 * сразу за ним скептик, которому поставлена задача КАЖДУЮ правку опровергнуть,
 * а не согласиться. Партии идут конвейером: скептик по первой работает, пока
 * проверяющий разбирает третью.
 *
 * Почему скептик отдельным агентом
 * --------------------------------
 * Тот же агент, который предложил правку, плохой её судья. На первых двухстах
 * словах скептик снял 3 правки из 41 и, что важнее, нашёл то, чего никто не
 * искал: знак ударения, стоящий внутри слогового начала (ʔˈet) — системная
 * ошибка генератора транскрипции, задевающая весь словарь, а не проверяемый
 * диапазон.
 *
 * Что делать с результатом
 * ------------------------
 * Подтверждённые правки НЕ применяются автоматически: их надо прогнать через
 * apply_review.py, который проверяет каждую по своему полю. На тех же первых
 * двухстах он поймал проверяющего, пронумеровавшего правки по порядку вместо
 * ранга, — пять правок указывали на другие слова.
 */

export const meta = {
  name: 'hebrew-adjudicate',
  description: 'Разбор расхождений словаря иврита с внешними источниками по диапазону рангов',
  phases: [
    { title: 'Разбор', detail: 'по 50 слов на проверяющего: все поля против всех источников' },
    { title: 'Оспаривание', detail: 'независимый скептик пытается опровергнуть каждую правку' },
    { title: 'Сводка', detail: 'что применять, что оставить, что вынести человеку' },
  ],
}

const DOSSIER = '/home/tony/repos/words/words/data/hebrew_freq/dossier_1000.jsonl'
// args может прийти и объектом, и JSON-строкой — при строке args.from молча
// undefined, и весь прогон уезжает на значения по умолчанию. Один диапазон уже
// был так пересчитан заново вместо следующего.
const A = typeof args === 'string' ? JSON.parse(args) : (args || {})
const FROM = A.from || 1
const TO = A.to || 200
const STEP = A.step || 50
if (!A.from || !A.to) throw new Error('не переданы границы диапазона: from/to')

const RULES = `
Проверяется словарь иврита для приложения интервального повторения. Каждая запись —
это СЛОВО ИЗ ЧАСТОТНОГО СПИСКА, то есть часто конкретная СЛОВОФОРМА (причастие,
форма лица, приставочная форма), а не словарная форма. Учащийся видит карточку:
огласованное написание, транскрипцию (IPA и русскими буквами), перевод.

Досье: ${DOSSIER}, JSONL, по строке на слово, поле "rank". Читай ТОЛЬКО свой диапазон,
например: awk 'NR>=1 && NR<=50' файл  — но надёжнее фильтровать по rank через python/jq.
Поля записи:
  ours   — что у нас сейчас: niqqud, ipa, translit_ru, russian, pos, lemma
  en     — английский Викисловарь; via="форма" про само написание, via="лемма" про лемму
  ru     — русский Викисловарь
  gtx    — машинный перевод (слабое свидетельство, голосует наравне, не решает)
  wd     — лексемы Викиданных
  issues — расхождения, найденные механически (могут быть и ложные)

ЖЁСТКИЕ ПРАВИЛА
1. Огласовка не меняет буквенный состав слова. Если снять все знаки с предложенной
   огласовки, обязано получиться исходное написание из поля "hebrew". Исключение —
   вав и йод как матери чтения (ktiv male/haser). Нарушение = предложение недопустимо.
2. Никаких правок без опоры на источник из досье. Свою эрудицию используй, чтобы
   ВЫБРАТЬ между вариантами источников и отсеять неподходящие, а не чтобы выдумать
   третий вариант, которого нигде нет.
3. Часть речи — строго из набора: сущ, глаг, прил, нареч, мест, предл, союз, межд,
   част, числ, имя. Часть речи СЛОВОФОРМЫ, а не леммы.
4. IPA — современный израильский, не библейский и не ашкеназский.
5. Перевод выбирается ПО ПОЛЬЗЕ ДЛЯ ИЗУЧЕНИЯ:
   - у словоформы перевод должен быть в той же форме («хочет», а не «хотеть»),
     потому что учащийся встретит именно её;
   - у многозначного слова — сначала основное значение, потом остальные;
   - перевод короткий: он же попадает в кнопку варианта ответа в режиме выбора;
   - помета рода/лица полезна, если форма их различает: «знаю, знает (м)».
   Если наш перевод уже лучше того, что дают источники — так и скажи, правка не нужна.
6. Расхождение само по себе НЕ ошибка. Викисловарь даёт лемму там, где у нас форма;
   у приставочной формы часть речи законно другая; омонимия — не ошибка.
   Оставить как есть — полноценный и частый ответ.

ЧТО ДЕЛАТЬ С ОМОГРАФАМИ
Если одно написание — это разные слова (עם «с» и עם «народ»), НЕ переписывай перевод
в кашу. Предложи field="tones": там у нас хранятся варианты чтения, каждый со своей
огласовкой, IPA и значением. Формат строки:
  <b>עם</b>: <i>вариантов огласовки: 2</i>
   - <b>עִם</b> [ʔim]: с, вместе с
   - <b>עַם</b> [ʔam]: народ
Основное чтение при этом остаётся в niqqud/ipa/russian.
`

const PROPOSAL_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['range', 'checked', 'proposals', 'notes'],
  properties: {
    range: { type: 'string' },
    checked: { type: 'integer', description: 'сколько слов реально просмотрено' },
    proposals: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['rank', 'hebrew', 'field', 'current', 'proposed', 'reason', 'confidence'],
        properties: {
          rank: { type: 'integer' },
          hebrew: { type: 'string' },
          field: { type: 'string', enum: ['niqqud', 'ipa', 'translit_ru', 'russian', 'pos', 'lemma', 'tones'] },
          current: { type: 'string' },
          proposed: { type: 'string' },
          reason: { type: 'string', description: 'почему, со ссылкой на источник' },
          sources: { type: 'string', description: 'какие источники это подтверждают' },
          confidence: { type: 'string', enum: ['высокая', 'средняя', 'низкая'] },
        },
      },
    },
    notes: { type: 'string', description: 'наблюдения: систематические проблемы, слова для человека' },
  },
}

const VERDICT_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['verdicts'],
  properties: {
    verdicts: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['rank', 'field', 'verdict', 'why'],
        properties: {
          rank: { type: 'integer' },
          field: { type: 'string' },
          verdict: { type: 'string', enum: ['подтверждено', 'отклонено', 'спорно'] },
          why: { type: 'string' },
          better: { type: 'string', description: 'если есть вариант лучше предложенного' },
        },
      },
    },
  },
}

const batches = []
for (let a = FROM; a <= TO; a += STEP) {
  batches.push({ from: a, to: Math.min(a + STEP - 1, TO) })
}
log(`диапазон ${FROM}–${TO}, партий: ${batches.length} по ${STEP} слов`)

phase('Разбор')
const results = await pipeline(
  batches,
  b => agent(`${RULES}

Твой диапазон: ранги ${b.from}–${b.to} включительно. Просмотри КАЖДОЕ слово диапазона,
а не только те, у которых непустое issues — механический поиск расхождений неполон.
Для каждого поля реши: оставить как есть или изменить. Предлагай правку только тогда,
когда уверен, что станет ЛУЧШЕ ДЛЯ ИЗУЧЕНИЯ.
В "checked" укажи, сколько слов ты реально просмотрел — если меньше диапазона, скажи почему.`,
    { label: `разбор:${b.from}-${b.to}`, phase: 'Разбор', schema: PROPOSAL_SCHEMA }),

  (res, b) => {
    if (!res || !res.proposals || res.proposals.length === 0) return { batch: b, proposals: [], verdicts: [] }
    return agent(`${RULES}

Ты СКЕПТИК. Ниже — правки, предложенные другим проверяющим по рангам ${b.from}–${b.to}.
Твоя задача — попытаться КАЖДУЮ опровергнуть, а не согласиться. Проверь по досье
${DOSSIER} (ранги ${b.from}–${b.to}), что источник действительно говорит то, что
приписано, и что правка не нарушает жёсткие правила.

Отклоняй, если: буквенный состав слова меняется; источник процитирован неверно или
относится к лемме, а речь о форме; правка делает перевод хуже для изучения (заменяет
форму на инфинитив, удлиняет кнопку варианта, теряет помету рода); правка опирается
только на машинный перевод; «исправление» на самом деле равнозначный вариант.
При сомнении ставь "спорно", а не "подтверждено".

ПРАВКИ:
${JSON.stringify(res.proposals, null, 1)}`,
      { label: `скептик:${b.from}-${b.to}`, phase: 'Оспаривание', schema: VERDICT_SCHEMA })
      .then(v => ({ batch: b, proposals: res.proposals, notes: res.notes, checked: res.checked,
                    verdicts: (v && v.verdicts) || [] }))
  }
)

const good = results.filter(Boolean)
const allProposals = good.flatMap(r => r.proposals || [])
const allVerdicts = good.flatMap(r => r.verdicts || [])
const key = (rank, field) => `${rank}|${field}`
const vmap = new Map(allVerdicts.map(v => [key(v.rank, v.field), v]))

const enriched = allProposals.map(p => ({ ...p, verdict: (vmap.get(key(p.rank, p.field)) || {}).verdict || 'без вердикта',
                                          verdict_why: (vmap.get(key(p.rank, p.field)) || {}).why || '',
                                          better: (vmap.get(key(p.rank, p.field)) || {}).better || '' }))
const confirmed = enriched.filter(p => p.verdict === 'подтверждено')
const disputed = enriched.filter(p => p.verdict === 'спорно')
const rejected = enriched.filter(p => p.verdict === 'отклонено')

log(`предложено ${enriched.length}: подтверждено ${confirmed.length}, спорно ${disputed.length}, отклонено ${rejected.length}`)

phase('Сводка')
const summary = await agent(`Ты сводишь итог проверки словаря иврита по рангам ${FROM}–${TO}.

Ниже правки с вердиктами скептика. Составь по-русски краткий, плотный отчёт:
- сколько слов проверено, сколько правок подтверждено/спорно/отклонено;
- по полям: что систематически не так с нашими данными (это важнее списка правок);
- какие классы правок безопасно применять машинно, а какие требуют человека;
- 5-8 самых показательных примеров с объяснением, почему именно так лучше для изучения;
- что скептик отклонил чаще всего и о чём это говорит.
Без воды. Не перечисляй все правки подряд.

ПОДТВЕРЖДЕНО (${confirmed.length}):
${JSON.stringify(confirmed, null, 1).slice(0, 45000)}

СПОРНО (${disputed.length}):
${JSON.stringify(disputed, null, 1).slice(0, 20000)}

ОТКЛОНЕНО (${rejected.length}):
${JSON.stringify(rejected, null, 1).slice(0, 20000)}

ЗАМЕТКИ ПРОВЕРЯЮЩИХ:
${good.map(r => r.notes).filter(Boolean).join('\n---\n').slice(0, 15000)}`,
  { label: 'сводка', phase: 'Сводка' })

return {
  range: `${FROM}-${TO}`,
  checked: good.reduce((s, r) => s + (r.checked || 0), 0),
  counts: { proposed: enriched.length, confirmed: confirmed.length, disputed: disputed.length, rejected: rejected.length },
  confirmed,
  disputed,
  summary,
}
