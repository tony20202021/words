"""Транскрипция предложений по словам: правила склейки без базы.

Каждая проверка стоит на месте, где склейка уже ошибалась 09.11.2026, пока
транскрипцию для таблицы примеров собирали впервые.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from transcribe import (без_лишнего_ударения, одна_транскрипция, слово,  # noqa: E402
                        слогов, транскрибировать)


def test_английский_берёт_первый_вариант_словаря():
    """Второй вариант — сборная солянка: у she это диалектное hjoː."""
    assert одна_транскрипция("/ˈʃi/, /hjoː/", "en") == "ˈʃi"
    assert одна_транскрипция("/ˈəs/, /ˌjuˈɛs/, /ʌs/", "en") == "ˈəs"


def test_из_транскрипции_убирается_шум():
    """Неслоговой знак, скобки необязательного звука и тёмное l."""
    assert одна_транскрипция("/ˈɫaɪ̯k/", "en") == "ˈlaɪk"
    assert одна_транскрипция("/ˈdʌb(ə)l/", "en") == "ˈdʌbəl"


def test_дифтонг_один_слог_а_две_гласные_подряд_два():
    assert слогов("ˈmeɪk") == 1
    assert слогов("ˈtaɪm") == 1
    assert слогов("əˈbaʊt") == 2
    # snowing — snoʊ-ɪŋ: пока гласные подряд считались одним ядром, у таких
    # форм пропадало ударение.
    assert слогов("ˈsnoʊɪŋ") == 2
    assert слогов("ˈsiɪŋ") == 2


def test_у_односложного_ударение_снимается_у_многосложного_остаётся():
    assert без_лишнего_ударения("ˈðə") == "ðə"
    assert без_лишнего_ударения("ˈpipəl") == "ˈpipəl"
    assert без_лишнего_ударения("ˈsnoʊɪŋ") == "ˈsnoʊɪŋ"


ТР_АНГЛ = {"care": ["ˈkɛɹ"], "car": ["ˈkɑɹ"], "hate": ["ˈheɪt"], "hat": ["ˈhæt"],
           "teach": ["ˈtitʃ"], "just": ["ˈdʒəst"], "a": ["ˈeɪ"], "team": ["ˈtim"],
           "wash": ["ˈwɑʃ"], "kiss": ["ˈkɪs"], "deserve": ["dɪˈzɝv"]}


def test_окончание_s_пробуется_раньше_es():
    """Иначе cares разбиралось как car + es, а hates — как hat + es."""
    assert слово("cares", ТР_АНГЛ, "en")[0] == "ˈkɛɹz"
    assert слово("hates", ТР_АНГЛ, "en")[0] == "ˈheɪts"
    assert слово("teaches", ТР_АНГЛ, "en")[0] == "ˈtitʃɪz"


def test_окончания_по_звучанию_основы():
    assert слово("washed", ТР_АНГЛ, "en")[0] == "ˈwɑʃt"
    assert слово("kissed", ТР_АНГЛ, "en")[0] == "ˈkɪst"
    assert слово("deserved", ТР_АНГЛ, "en")[0] == "dɪˈzɝvd"
    assert слово("team's", ТР_АНГЛ, "en")[0] == "ˈtimz"


def test_наречие_на_ly():
    """justly своей статьи не имеет — была дыра «?» в транскрипции."""
    assert слово("justly", ТР_АНГЛ, "en")[0] == "ˈdʒəstli"


def test_артикль_a_во_фразе_звучит_слабо():
    """В словаре a — eɪ, как буква алфавита; в «a book» это ə."""
    assert слово("a", ТР_АНГЛ, "en")[0] == "ə"


ТР_ИВРИТ = {"לך": ["leˈχa", "laχ"], "זמן": ["zman"], "יש": ["jeʃ"],
            "בית": ["ˈbajit"]}


def test_у_омографа_берётся_самая_частая_статья_и_ставится_пометка():
    """לְךָ (№11) раньше לָךְ (№9514): словарь отдаёт статьи по номеру."""
    тр, пометка = слово("לך", ТР_ИВРИТ, "he")
    assert тр == "leˈχa"
    assert "омограф" in пометка


def test_приставка_склеивается_и_идёт_на_проверку():
    """После ב/ל/כ артикль выпадает из письма: склейка — черновик, не истина."""
    тр, пометка = слово("ובית", ТР_ИВРИТ, "he")
    assert тр == "veˈbajit"
    assert "приставка" in пометка


def test_неизвестное_слово_видно_знаком_вопроса():
    строка, пометки = транскрибировать("יש משהו", ТР_ИВРИТ, "he")
    assert строка == "jeʃ ?"
    assert any("нет в словаре" in п for п in пометки)


def test_огласовки_в_тексте_не_мешают():
    строка, _ = транскрибировать("יֵשׁ זְמַן", ТР_ИВРИТ, "he")
    assert строка == "jeʃ zman"
