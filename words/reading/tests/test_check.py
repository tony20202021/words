"""
Проверка состава предложения: главный сторож затеи с текстами.

Смысл текстов для чтения в том, что человек их ПОНИМАЕТ: предложение собрано
из слов, которые он уже прошёл. Одно чужое слово — и предложение перестаёт
быть понятным входом, ради которого всё затевалось.

Поэтому проверка машинная. Сочиняет предложения тот, кто языком владеет, и
лишнее слово у него проскакивает незаметно — не по небрежности, а потому что
кажется само собой разумеющимся.

Проверка обязана знать морфологию. Без неё она врёт в обе стороны: бракует
«cats», потому что в словаре «cat», и пропускает мимо ушей приставки иврита,
из-за чего «הבית» не узнаётся как «בית».
"""
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from check import ключ_повтора, проверить, слова_текста   # noqa: E402
from vocabulary import без_огласовок, собрать      # noqa: E402


# ── английский ──────────────────────────────────────────────────────────────

АНГЛИЙСКИЕ = [{"word_number": n, "word": w} for n, w in enumerate(
    ["the", "to", "and", "of", "a", "in", "is", "for", "that", "you",
     "it", "on", "with", "this", "was", "be", "as", "are", "have", "at",
     "he", "not", "but", "from", "go", "see", "big", "house", "cat", "run"], 1)]


def англ(до=30, всегда=10):
    return собрать(АНГЛИЙСКИЕ, до_номера=до, всегда_первые=всегда, язык="en")


def test_предложение_из_известных_слов_годится():
    assert проверить("The cat is in the house.", "cat", англ()).годится


def test_чужое_слово_называется_поимённо():
    """Молчаливый отказ бесполезен: надо знать, какое слово лишнее."""
    итог = проверить("The cat is purple.", "cat", англ())
    assert not итог.годится
    assert итог.чужие == ["purple"]
    assert "purple" in итог.объясни()


def test_множественное_число_узнаётся():
    """
    Без морфологии сторож забраковал бы «cats», потому что в словаре «cat», —
    и половина годных предложений ушла бы в брак.
    """
    assert проверить("The cats are big.", "cat", англ()).годится


def test_нерегулярная_форма_узнаётся():
    """«goes» обратной морфологией из «go» не выводится — нужен список."""
    assert проверить("The cat goes to the house.", "cat", англ()).годится


def test_прошедшее_время_узнаётся():
    assert проверить("The cat ran to the house.", "cat", англ()).годится


def test_предложение_без_целевого_слова_не_годится():
    """Предложение должно быть про слово, иначе оно не для этой карточки."""
    итог = проверить("The house is big.", "cat", англ())
    assert not итог.годится and итог.нет_целевого


def test_целевое_слово_засчитывается_в_любой_форме():
    """Человек встретит слово склонённым — требовать словарную форму глупо."""
    assert проверить("The cats are big.", "cat", англ()).годится


def test_слово_за_границей_номера_не_проходит():
    """
    Опора под всем правилом. «run» есть в словаре, но у него номер 30, а
    человек дошёл только до двадцатого слова.
    """
    итог = проверить("You run to the house.", "house", англ(до=20, всегда=10))
    assert not итог.годится
    assert "run" in итог.чужие


def test_первые_слова_разрешены_всегда():
    """
    Для слова №5 разрешено пять слов — предложения не построить. Нижняя
    граница на то и заведена: служебные слова доступны с самого начала.
    """
    словарь = собрать(АНГЛИЙСКИЕ, до_номера=5, всегда_первые=20, язык="en")
    # Слова взяты из первой двадцатки: «not» и «house» идут позже, и с ними
    # проверка мерила бы не нижнюю границу, а собственную невнимательность.
    assert проверить("You have this.", "this", словарь).годится


def test_знаки_препинания_словами_не_считаются():
    assert проверить("The cat, the house — and you!", "cat", англ()).годится


# ── иврит ───────────────────────────────────────────────────────────────────

ИВРИТСКИЕ = [
    {"word_number": 1, "word_foreign": "אֲנִי", "lemma": "אני"},
    {"word_number": 2, "word_foreign": "לֹא", "lemma": "לא"},
    {"word_number": 3, "word_foreign": "זֶה", "lemma": "זה"},
    {"word_number": 4, "word_foreign": "יֵשׁ", "lemma": "יש"},
    {"word_number": 5, "word_foreign": "בַּיִת", "lemma": "בית"},
    {"word_number": 6, "word_foreign": "גָּדוֹל", "lemma": "גדול"},
    {"word_number": 7, "word_foreign": "סֵפֶר", "lemma": "ספר"},
]


def ивр(до=7, всегда=7):
    return собрать(ИВРИТСКИЕ, до_номера=до, всегда_первые=всегда, язык="he")


def test_огласовки_не_мешают_узнать_слово():
    """В тексте слово может стоять без огласовки — это та же единица."""
    assert проверить("אני לא זה", "אני", ивр()).годится


def test_приставка_не_мешает_узнать_слово():
    """
    Приставки מש"ה וכל"ב пишутся слитно. Без их отрезания «הבית» осталось бы
    неузнанным, и годное предложение ушло бы в брак.
    """
    итог = проверить("הבית גדול", "בית", ивр())
    assert итог.годится, итог.объясни()


def test_двойная_приставка_тоже_отрезается():
    """«ובבית» — союз плюс предлог: обе буквы приставочные."""
    итог = проверить("ובבית יש ספר", "ספר", ивр())
    assert итог.годится, итог.объясни()


def test_чужое_слово_на_иврите_ловится():
    итог = проверить("אני אוהב קוואנטום", "אני", ивр())
    assert not итог.годится
    assert "קוואנטום" in итог.чужие


def test_целевое_слово_с_приставкой_засчитывается():
    """В тексте целевое слово тоже может стоять с приставкой."""
    assert проверить("הבית גדול", "בית", ивр()).годится


def test_огласовка_снимается():
    assert без_огласовок("בַּיִת") == "בית"


def test_слова_текста_разбирают_обе_письменности():
    assert слова_текста("The cat.") == ["The", "cat"]
    assert слова_текста("אני לא") == ["אני", "לא"]


# ── поздние формы: прошли морфологией, а свой номер за пределом ─────────────
#
# Нашлось формальной проверкой уже сочинённого. Предложение «זה כל מה שיש»
# сторож пропустил: שיש разбирается как ש + יש, а יש — слово №18. Но в словаре
# שיש стоит ОТДЕЛЬНОЙ статьёй под №121, и человек, прошедший сотню слов, до
# неё не дошёл. То же с הזמן: ה + זמן (№87), своя статья — №151.
#
# Бракуется ли такое? Нет. Артикль не делает текст непонятным, а запрет
# артикля сделал бы иврит неживым. Но назвать это надо, иначе про такие формы
# не узнает никто: сторож, умеющий отвечать только «да», их и прячет.

СЛОВАРЬ_С_ПРИСТАВОЧНОЙ = [
    {"word_number": 1, "word": "זה", "lemma": "זה"},
    {"word_number": 2, "word": "כל", "lemma": "כל"},
    {"word_number": 5, "word": "זמן", "lemma": "זמן"},
    {"word_number": 8, "word": "יש", "lemma": "יש"},
    # Приставочные формы тех же слов — своими статьями, далеко за пределом.
    {"word_number": 20, "word": "הזמן", "lemma": "זמן"},
    {"word_number": 25, "word": "שיש", "lemma": "יש"},
]


def ивр_с_приставочной(до=5, всегда=10):
    return собрать(СЛОВАРЬ_С_ПРИСТАВОЧНОЙ, до_номера=до, всегда_первые=всегда,
                   язык="he")


def test_приставочная_форма_со_своим_номером_называется():
    итог = проверить("זה הזמן", "זמן", ивр_с_приставочной())
    assert итог.годится, "понятность не страдает — брака быть не должно"
    assert итог.поздние == [("הזמן", 20)]
    assert "№20" in итог.оговорки()


def test_слово_внутри_предела_поздним_не_считается():
    """Иначе оговорка появлялась бы у каждого второго предложения."""
    итог = проверить("זה כל", "כל", ивр_с_приставочной())
    assert итог.годится
    assert итог.поздние == []
    assert итог.оговорки() == ""


def test_номера_известны_и_для_запредельных_слов():
    """
    Прежний словарь складывал только разрешённые слова: про שיש он не знал
    ничего и сказать «её номер 25» не мог.
    """
    словарь = ивр_с_приставочной()
    assert словарь.свой_номер("שיש") == 25
    assert словарь.свой_номер("זמן") == 5
    assert словарь.свой_номер("ואללה") is None
    assert словарь.за_пределом("שיש")
    assert not словарь.за_пределом("זמן")


def test_огласованная_форма_узнаётся_по_своему_номеру():
    """В словаре слова с огласовкой, в тексте — без: ключ должен совпасть."""
    assert ивр_с_приставочной().свой_номер("הַזְּמַן") == 20


# ── повторы ─────────────────────────────────────────────────────────────────
#
# «I know you» годится и для you, и для i, и для know — нарушения состава
# нет. Но человеку, встретившему одну фразу третий раз, она третий раз не
# даёт ничего. Поэтому фраза живёт в файле однажды.


def test_повтор_не_зависит_от_регистра_и_точки():
    assert ключ_повтора("The time is good.", "en") == \
           ключ_повтора("the time is good", "en")


def test_разные_предложения_разные_ключи():
    assert ключ_повтора("I know you", "en") != ключ_повтора("You know me", "en")


def test_повтор_на_иврите_не_зависит_от_огласовки():
    assert ключ_повтора("זֶה הַזְּמַן", "he") == ключ_повтора("זה הזמן", "he")


def test_порядок_слов_в_ключе_сохраняется():
    """Иначе «I know you» и «You know I» слились бы в одно предложение."""
    assert ключ_повтора("i know you", "en") != ключ_повтора("you know i", "en")


# ── невыводимые формы: брак, а не оговорка ──────────────────────────────────
#
# Нашлось на второй порции английского. Предложение «At first I did not know»
# сторож пропускал: «did» сводится к «do» (№50), всё разрешено. Но «did» стоит
# в словаре своей статьёй под №112, и вывести его из «do» нельзя — никакое
# правило из «do» не даёт «did», это надо знать. Человек, прошедший сотню
# слов, спотыкается на втором слове.
#
# Оттого путь опознания и важен. Иврит: הזמן = ה + זמן, артикль человек
# выведет — оговорка. Английский: did, does, made, done — выводится ничем,
# значит брак. Прежний сторож обе беды сваливал в одну оговорку и предложение
# пропускал.

НЕВЫВОДИМЫЕ_СЛОВА = [
    {"word_number": 1, "word": "i"},
    {"word_number": 2, "word": "not"},
    {"word_number": 3, "word": "know"},
    {"word_number": 5, "word": "do"},
    {"word_number": 6, "word": "he"},
    {"word_number": 7, "word": "see"},
    # Нерегулярная форма «do» — своей статьёй, далеко за пределом.
    {"word_number": 20, "word": "did"},
    # Регулярная форма «see»: её человек выведет сам, хотя статья тоже поздняя.
    {"word_number": 25, "word": "sees"},
]


def англ_с_формами(до=7, всегда=10):
    return собрать(НЕВЫВОДИМЫЕ_СЛОВА, до_номера=до, всегда_первые=всегда,
                   язык="en")


def test_нерегулярная_форма_за_пределом_бракуется():
    итог = проверить("I did not know", "do", англ_с_формами())
    assert not итог.годится, "«did» из «do» не выводится — это брак"
    assert итог.непосильные == [("did", 20, "do")]
    assert "did" in итог.объясни() and "№112" not in итог.объясни()
    assert "№20" in итог.объясни()


def test_регулярная_форма_за_пределом_только_оговаривается():
    """
    «sees» из «see» выводится правилом, и бракуй его — пропали бы все
    третьи лица и все множественные числа.
    """
    итог = проверить("I know he sees", "see", англ_с_формами())
    assert итог.годится
    assert итог.непосильные == []
    assert итог.поздние == [("sees", 25)]


def test_приставка_иврита_остаётся_оговоркой_а_не_браком():
    """Артикль человек выведет: бракуй его — иврит стал бы неживым."""
    итог = проверить("זה הזמן", "זמן", ивр_с_приставочной())
    assert итог.годится
    assert итог.непосильные == []
    assert итог.поздние == [("הזמן", 20)]


def test_путь_опознания_называется():
    словарь = англ_с_формами()
    assert словарь.опознать("do") == ("точно", "do")
    assert словарь.опознать("did") == ("нерегулярная", "do")
    assert словарь.опознать("sees") == ("окончание", "see")
    assert словарь.опознать("purple") == (None, "purple")
