#!/usr/bin/env python3
"""Транскрипция предложений для чтения — по словам, из словаря.

Владелец (09.11.2026): таблица примеров — четыре колонки, как у однокоренных,
и четвёртая — транскрипция. Своей транскрипции у предложений не было: только
текст и перевод.

ОТКУДА БЕРЁТСЯ. Каждое слово предложения уже есть в словаре — так их и
сочиняли, — а у слова в словаре есть транскрипция. Значит предложение
транскрибируется склейкой слов. Это не фонетика целой фразы (слияний и
ассимиляций на стыках здесь нет), но для чтения по слогам её и не нужно.

ГДЕ СКЛЕЙКА ВРЁТ — и почему здесь не только машина.
  Иврит без огласовок: одно написание, разные слова. את — это и «эт»
  (показатель дополнения, №1), и «ат» («ты», ж. р.), а в словаре статья одна —
  первая. Машина такое не различит, различает смысл. Поэтому транскрипция
  записывается в файл предложений полем "tr" и дальше правится руками: этот
  скрипт заполняет только ПУСТЫЕ поля и ничего, что уже лежит, не трогает.
  Приставки מש"ה וכל"ב, если формы нет в словаре целиком, склеиваются по
  правилу (ב + бáйит → be + ...) — и тоже выводятся в список на проверку:
  после ב/ל/כ артикль выпадает из письма, и «בבית» — это «ба-бáйит».
  Английский: формы вроде loves, wears своих статей не имеют и выводятся из
  основы по правилу окончания — тоже в список.

Английская транскрипция в словаре — несколько вариантов через запятую. Берётся
ПЕРВЫЙ: он однородный, американский, из одного источника. Остальные — сборная
солянка: у she вторым идёт диалектное hjoː, у who — hw, у us — «ю-эс», то есть
сокращение U.S. Я сначала взял второй ради слабых форм служебных слов и получил
ровно это. Минус первого — ударение на каждом слове, даже на «the»; у
односложных его здесь снимаем: в односложном слове ударению негде выбирать.

Примеры:
    python reading/transcribe.py --language he            # что будет и что спорно
    python reading/transcribe.py --language he --apply    # записать пустые поля
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУТ))

from batches import ЯЗЫКИ, писать, читать          # noqa: E402
from check import слова_текста                      # noqa: E402
from vocabulary import ПРИСТАВКИ_ИВРИТА, без_огласовок  # noqa: E402

# Чтение слитной приставки без артикля. После ב/ל/כ артикль в письме выпадает,
# поэтому «бе» может оказаться «ба» — такие склейки идут на проверку.
ПРИСТАВКА_ЗВУК = {"ה": "ha", "ו": "ve", "ב": "be", "ל": "le", "מ": "mi",
                  "כ": "ke", "ש": "ʃe"}

ГЛУХИЕ = set("ptkfθ")
СВИСТЯЩИЕ = ("s", "z", "ʃ", "ʒ", "tʃ", "dʒ")


def одна_транскрипция(сырая: str, язык: str) -> str:
    """Из словарной строки — одна транскрипция без косых и скобок."""
    варианты = [в.strip().strip("/[]").strip() for в in (сырая or "").split(",")]
    варианты = [в for в in варианты if в]
    if not варианты:
        return ""
    в = варианты[0]
    # Неслоговой знак и скобки необязательного звука для фразы — шум.
    return в.replace("̯", "").replace("(", "").replace(")", "").replace("ɫ", "l")


ГЛАСНЫЕ = set("aeiouyæɑɒɔəɛɜɝɚɪʊʌɐɨʉøœ")


def слогов(тр: str) -> int:
    """Сколько гласных ядер.

    Дифтонг — одно ядро: eɪ, aɪ, aʊ, oʊ, ɔɪ — гласная плюс скольжение ɪ/ʊ.
    Любая другая пара гласных подряд — уже два слога: snowing — это snoʊ-ɪŋ,
    seeing — si-ɪŋ. Пока подряд идущие гласные считались одним ядром,
    у таких форм пропадало ударение, как у односложных.
    """
    ядер, прежняя = 0, ""
    for буква in тр:
        if буква in "ːˈˌ.":
            continue
        if буква in ГЛАСНЫЕ:
            скольжение = буква in "ɪʊ" and прежняя in "aeoɔ"
            if not прежняя or not скольжение:
                ядер += 1
            прежняя = буква
        else:
            прежняя = ""
    return ядер


def без_лишнего_ударения(тр: str) -> str:
    """У односложного слова знак ударения ничего не сообщает — снимаем."""
    if слогов(тр) <= 1:
        return тр.replace("ˈ", "").replace("ˌ", "")
    return тр


def словарь_транскрипций(язык: str) -> dict:
    """написание без огласовок → транскрипции статей, самая частая первой.

    Порядок по номеру, а не по алфавиту: у омографа без огласовок читается
    по умолчанию частое слово. לך — это לְךָ (№11, «лехá») раньше, чем
    לָךְ (№9514, «лах»); по алфавиту выходило наоборот.
    """
    from pymongo import MongoClient
    db = MongoClient("mongodb://localhost:8527",
                     serverSelectionTimeoutMS=5000)["language_learning_bot"]
    яз = db.languages.find_one({"name_ru": ЯЗЫКИ[язык]})
    out = defaultdict(list)
    for w in db.words.find({"language_id": яз["_id"]},
                           {"word_foreign": 1, "transcription": 1,
                            "word_number": 1}).sort("word_number", 1):
        ключ = без_огласовок(w.get("word_foreign") or "").strip()
        ключ = ключ if язык == "he" else ключ.lower()
        т = одна_транскрипция(w.get("transcription") or "", язык)
        if ключ and т and т not in out[ключ]:
            out[ключ].append(т)
    return out


# Служебные слова, у которых словарная (ударная) форма во фразе не звучит:
# «a» в словаре — eɪ, как буква алфавита, а в «a book» это ə.
СЛАБЫЕ_АНГЛ = {"a": "ə", "an": "ən"}


def _окончание_англ(основа_тр: str, вид: str) -> str:
    """Транскрипция формы по транскрипции основы: -s/-'s, -ed, -ing."""
    if вид == "s":
        if основа_тр.endswith(СВИСТЯЩИЕ):
            return основа_тр + "ɪz"
        return основа_тр + ("s" if основа_тр[-1:] in ГЛУХИЕ else "z")
    if вид == "ed":
        if основа_тр.endswith(("t", "d")):
            return основа_тр + "ɪd"
        return основа_тр + ("t" if основа_тр[-1:] in ГЛУХИЕ | {"s", "ʃ"} else "d")
    if вид == "ly":
        return основа_тр + "li"
    return основа_тр + "ɪŋ"


def слово(с: str, тр: dict, язык: str):
    """(транскрипция, пометка). Пометка пустая — значит однозначно по словарю."""
    ключ = с if язык == "he" else с.lower()
    if язык == "en" and ключ in СЛАБЫЕ_АНГЛ:
        return СЛАБЫЕ_АНГЛ[ключ], ""
    if ключ in тр:
        варианты = тр[ключ]
        return варианты[0], ("" if len(варианты) == 1 else
                             "омограф: " + " / ".join(варианты))
    if язык == "he":
        for глубина in (1, 2):
            if len(ключ) > глубина + 1 and all(б in ПРИСТАВКИ_ИВРИТА
                                               for б in ключ[:глубина]):
                хвост = ключ[глубина:]
                if хвост in тр:
                    приставка = "".join(ПРИСТАВКА_ЗВУК[б] for б in ключ[:глубина])
                    return (приставка + тр[хвост][0],
                            f"приставка {ключ[:глубина]} + {хвост}")
        return "", "нет в словаре"
    # Английский: притяжательное и окончания.
    if ключ.endswith("'s") and ключ[:-2] in тр:
        return _окончание_англ(тр[ключ[:-2]][0], "s"), "форма от " + ключ[:-2]
    # «s» раньше «es»: иначе cares разбиралось как car + es, hates — как hat.
    for конец, вид, замена in (("ies", "s", "y"), ("s", "s", ""), ("es", "s", ""),
                               ("ied", "ed", "y"), ("ed", "ed", ""), ("ed", "ed", "e"),
                               ("ing", "ing", ""), ("ing", "ing", "e"),
                               ("ly", "ly", "")):
        if ключ.endswith(конец):
            основа = ключ[:-len(конец)] + замена
            if основа in тр:
                return _окончание_англ(тр[основа][0], вид), "форма от " + основа
    return "", "нет в словаре"


def транскрибировать(текст: str, тр: dict, язык: str):
    """(транскрипция предложения, [пометки]) — слова через пробел."""
    части, пометки = [], []
    for с in слова_текста(без_огласовок(текст)):
        т, пометка = слово(с, тр, язык)
        if т and язык == "en":
            т = без_лишнего_ударения(т)
        части.append(т or "?")
        if пометка:
            пометки.append(f"{с}: {пометка}")
    return " ".join(части), пометки


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--language", choices=list(ЯЗЫКИ), required=True)
    p.add_argument("--apply", action="store_true",
                   help="записать в файл предложений (только пустые поля tr)")
    a = p.parse_args(argv)

    тр = словарь_транскрипций(a.language)
    данные = читать(a.language)
    заполнено, спорные = 0, []
    for номер, список in данные.items():
        for п in список:
            if (п.get("tr") or "").strip():
                continue                     # правленное руками не трогаем
            строка, пометки = транскрибировать(п["text"], тр, a.language)
            п["tr"] = строка
            заполнено += 1
            if пометки:
                спорные.append((номер, п["text"], строка, пометки))

    print(f"язык: {ЯЗЫКИ[a.language]}; заполнено бы: {заполнено}; спорных: {len(спорные)}")
    for номер, текст, строка, пометки in спорные:
        print(f"  №{номер} «{текст}» → [{строка}]  ({'; '.join(пометки)})")
    if a.apply:
        писать(a.language, данные)
        print("записано")
    else:
        print("[без --apply] не записано")
    return 0


if __name__ == "__main__":
    sys.exit(main())
