"""Какие слова человеку уже известны — и как узнать слово в тексте.

Предложения для чтения собираются из слов, которые человек уже прошёл: только
слова с номером не больше целевого. Это не формальность, а весь смысл затеи —
непонятный текст для усвоения бесполезен. Значит состав надо проверять
машинно: доверять тому, кто текст сочинил (человеку или модели), нельзя —
лишнее слово проскакивает незаметно.

Проверка опирается на морфологию, иначе она врёт в обе стороны. «goes» нет в
словаре, а «go» есть, и формально предложение нарушает правило, хотя по сути
нет. В иврите хуже: к слову спереди липнут приставки מש"ה וכל"ב, и הַסֵּפֶר
надо узнать как סֵפֶר.

НИЖНЯЯ ГРАНИЦА. Для слова №30 разрешено тридцать слов — предложение из них не
построить. Поэтому несколько первых слов разрешены всегда: служебные,
предлоги, местоимения, связки. Сколько именно — настройка, по умолчанию сто.

СВОЙ НОМЕР У ФОРМЫ. Морфология разрешает лишнее. Форма הַזְּמַן узнаётся как
ה + זְמַן (№87) и проходит — но в словаре она стоит ОТДЕЛЬНОЙ статьёй под
№151, то есть сама по себе за пределом. Разбор, который видит только «да»,
такое не покажет, а это ровно то, о чём стоит знать: через морфологию в текст
попало слово, до которого человек не дошёл. Поэтому словарь держит номера всех
слов языка, а не только разрешённых, и умеет сказать свой номер любой формы.
"""
