def без_огласовок(текст: str) -> str:
    return ОГЛАСОВКИ.sub("", текст or "")


@dataclass
class Словарь:
    """Разрешённые слова для одного языка и одного уровня."""

    язык: str
    разрешено: Set[str] = field(default_factory=set)
    # Для иврита: лемма -> та же лемма; помогает узнать форму с приставкой.
    леммы: Set[str] = field(default_factory=set)
    # Номера ВСЕХ слов языка, включая запредельные: нужны, чтобы назвать
    # номер формы, прошедшей через морфологию.
    номера: Dict[str, int] = field(default_factory=dict)
    предел: int = 0

    def свой_номер(self, слово: str):
        """Номер формы как отдельной словарной статьи, если такая есть."""
        return self.номера.get(self._ключ(слово))

    def за_пределом(self, слово: str) -> bool:
        """Форма стоит в словаре отдельной статьёй, и её номер за пределом."""
        н = self.свой_номер(слово)
        return н is not None and self.предел and н > self.предел

    def _ключ(self, слово: str) -> str:
        с = без_огласовок(слово or "").strip()
        return с if self.язык == "he" else с.lower().strip("'")

    # Пути, по которым форма выводится из разрешённого слова своими силами.
    # «goes» из «go» человек выведет — правило регулярное. «did» из «do» не
    # выведет никак: это надо знать. Разница существенная, поэтому путь
    # опознания возвращается наружу, а не теряется внутри «да/нет».
    ВЫВОДИМЫЕ = ("точно", "лемма", "пусто", "окончание", "приставка",
                 "апостроф")

    def знает(self, слово: str) -> bool:
        """Входит ли слово из текста в разрешённый набор."""
        return self.опознать(слово)[0] is not None

    def опознать(self, слово: str):
        """(путь, основа) или (None, слово) — каким путём слово узнано."""
        if self.язык == "he":
            return self._опознать_иврит(слово)
        return self._опознать_английский(слово)

    # ── английский ─────────────────────────────────────────────────────────

    def _опознать_английский(self, слово: str):
        с = слово.lower().strip("'")
        if not с:
            return ("пусто", с)            # пунктуация словом не считается
        if с in self.разрешено:
            return ("точно", с)
        # Окончания пробуются ПЕРЕД таблицей, и порядок тут не случаен.
        # В НЕРЕГУЛЯРНЫЕ ради удобства попали и вполне регулярные формы —
        # sees, goes, knows, makes. Спроси таблицу первой, и «sees» объявится
        # невыводимым, хотя человек выводит его правилом про -s. Таблица
        # должна отвечать только там, где правило не справилось.
        for к, зам in ОКОНЧАНИЯ:
            if с.endswith(к) and len(с) - len(к) >= 2:
                основа = с[:len(с) - len(к)] + зам
                if основа in self.разрешено:
                    return ("окончание", основа)
        осн = НЕРЕГУЛЯРНЫЕ.get(с)
        if осн in self.разрешено:
            return ("нерегулярная", осн)
        # Притяжательное и сокращения: «John's», «don't» — проверяем основу.
        if "'" in с:
            голова = с.split("'")[0]
            if голова in self.разрешено:
                return ("апостроф", голова)
            if НЕРЕГУЛЯРНЫЕ.get(голова) in self.разрешено:
                return ("апостроф", НЕРЕГУЛЯРНЫЕ[голова])
        return (None, с)

    # ── иврит ──────────────────────────────────────────────────────────────

    def _опознать_иврит(self, слово: str):
        с = без_огласовок(слово).strip()
        if not с:
            return ("пусто", с)
        if с in self.разрешено:
            return ("точно", с)
        if с in self.леммы:
            return ("лемма", с)
        # Приставки пишутся слитно и могут идти парой: ושה, ולב и подобное.
        for глубина in (1, 2):
            if len(с) <= глубина + 1:
                continue
            if all(б in ПРИСТАВКИ_ИВРИТА for б in с[:глубина]):
                хвост = с[глубина:]
                if хвост in self.разрешено or хвост in self.леммы:
                    return ("приставка", хвост)
        return (None, с)


def собрать(слова: list, до_номера: int, всегда_первые: int = 100,
            язык: str = "en") -> Словарь:
    """
    Словарь разрешённых слов.

    слова — записи вида {word_number, word_foreign, lemma?}, как в базе или
    в собранном словаре. Берутся все с номером не больше `до_номера`, плюс
    первые `всегда_первые` — без них для малых номеров предложение не из чего
    строить.
    """
    граница = max(до_номера, всегда_первые)
    d = Словарь(язык=язык, предел=граница)
    for w in слова:
        номер = w.get("word_number") or w.get("frequency") or 0
        форма = (w.get("word_foreign") or w.get("word") or "").strip()
        if not форма:
            continue
        ключ = (без_огласовок(форма) if язык == "he"
                else без_огласовок(форма).lower())
        # Номера знаем про все слова языка: по ним потом видно, что форма
        # прошла морфологией, а своей статьёй стоит далеко за пределом.
        if ключ and номер:
            d.номера[ключ] = min(d.номера.get(ключ, номер), номер)
        if номер > граница:
            continue
        d.разрешено.add(ключ)
        лемма = (w.get("lemma") or "").strip()
        if лемма:
            d.леммы.add(без_огласовок(лемма))
    return d
