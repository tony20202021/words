"""Озвучка предложений для чтения: какие голоса и где лежит каждый файл.

Владелец (21.11.2026): «пусть в базе будут сгенерированы все [голоса], но
каждый раз на телефон передаётся рандомно выбранный один». Поэтому у каждого
предложения в базе — список его готовых файлов (поле sounds), а один из них
выбирает карточка при сборке.

ГОЛОСА ТЕ ЖЕ, ЧТО У СЛОВ. У иврита — gTTS и два голоса Microsoft Edge (Hila и
Avri, каталоги gtts/hila/avri, как у слов в sounds/he/), у английского — те же
три, что ставит words/tts/gen_sounds.py.

ИМЯ ФАЙЛА — ОТ ТЕКСТА, а не от номера слова и места примера. Предложения
меняют, переставляют и заменяют по одному (так уже было 09.11.2026 с «אני
רוצה שני»); имя по месту указывало бы после этого на чужой звук. Одинаковый
текст у двух слов получает один файл — и это правильно: звучит он одинаково.

Пути — относительно backend/data, как у звуков слов («sounds/he/gtts/4.mp3»):
бэкенд отдаёт их по /api/sounds/<путь>, служба логики — по /sounds/<путь>.
"""
import hashlib
import unicodedata
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2] / "language-learning-bot" / "backend" / "data"

# язык -> [(каталог, движок, параметр движка)]
#
# Четвёртый голос иврита — Piper, модель he_IL-noa-medium (CC BY 4.0, см.
# DATA_SOURCES.md). Владелец выбрал его 21.11.2026 по образцам, темп — «Б
# комфортнее всего»: на 20% медленнее и с короткой паузой между словами.
# Делает его words/tts/piper_noa.py в своём окружении (Python 3.12), а не
# gen_reading_sounds.py: тому этот движок недоступен.
ГОЛОСА = {
    "he": [("gtts", "gtts", "iw"),
           ("hila", "edge", "he-IL-HilaNeural"),
           ("avri", "edge", "he-IL-AvriNeural"),
           ("noa", "piper", "he_IL-noa-medium")],
    "en": [("gtts", "gtts", "en"),
           ("voice1", "edge", "en-US-AriaNeural"),
           ("voice2", "edge", "en-US-GuyNeural")],
}


def ключ(текст: str) -> str:
    """Имя файла по тексту: пробелы и форма записи букв на него не влияют."""
    ровный = unicodedata.normalize("NFC", " ".join(текст.split()))
    return hashlib.sha1(ровный.encode("utf-8")).hexdigest()[:16]


def путь(язык: str, голос: str, текст: str) -> str:
    return f"sounds/{язык}/reading/{голос}/{ключ(текст)}.mp3"


def готовые(язык: str, текст: str, корень: Path = КОРЕНЬ) -> list[str]:
    """Пути файлов этого предложения, которые уже есть и не пусты."""
    итог = []
    for голос, _, _ in ГОЛОСА[язык]:
        p = путь(язык, голос, текст)
        f = корень / p
        if f.is_file() and f.stat().st_size > 0:
            итог.append(p)
    return итог
