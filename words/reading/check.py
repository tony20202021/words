"""Проверка предложения: только из разрешённых слов и целевое слово внутри.

Два требования, и оба обязательны:

  1. Каждое слово текста известно человеку — иначе предложение непонятно, а
     непонятный текст для усвоения бесполезен.
  2. Целевое слово в предложении есть — иначе предложение не про него.

Проверка машинная намеренно. Сочиняет предложения тот, кто языком владеет, и
лишнее слово у него проскакивает незаметно: не потому что схалтурил, а потому
что оно кажется само собой разумеющимся.

Третье требование — не повторяться. «I know you» годится и для you, и для i,
и формально нарушения нет; но человеку, встретившему одну фразу трижды, она
третий раз ничего не даёт. Повтор считается по тексту без огласовок, регистра
и завершающей точки: «Это время.» и «это время» — одно и то же предложение.

ФОРМЫ СО СВОИМ НОМЕРОМ. Морфология пропускает слова, у которых есть своя
словарная статья за пределом разрешённого, — и тут всё зависит от того, каким
путём форма узнана.

  Выводимая своими силами — не брак, но оговорка. הַזְּמַן — это ה + זְמַן
  (№87): артикль человек выведет, хотя сама форма стоит под №151. Запрет на
  артикль сделал бы иврит неживым, поэтому предложение проходит. Но называть
  такие формы надо — иначе про них никто не узнает.

  Невыводимая — брак. «did» из «do» (№50) не выводится никаким правилом, это
  надо знать, а своя статья у «did» — №112. Человек, прошедший сотню слов, в
  предложении «At first I did not know» спотыкается на втором слове. Такие
  формы существуют только в английском: нерегулярные прошедшие и причастия.
"""
import re
from dataclasses import dataclass, field
from typing import List, Tuple

from vocabulary import Словарь, без_огласовок

# Слово в тексте: буквы латиницы или иврита, плюс апостроф и дефис внутри.
СЛОВО = re.compile(r"[A-Za-z֐-׾]+(?:['’׳-][A-Za-z֐-׾]+)*")


@dataclass
class Итог:
    годится: bool
    чужие: List[str]
    нет_целевого: bool
    # (форма, свой номер) — выводимые, но своей статьёй за пределом: оговорка.
    поздние: List[Tuple[str, int]] = field(default_factory=list)
    # (форма, свой номер, основа) — невыводимые и за пределом: брак.
    непосильные: List[Tuple[str, int, str]] = field(default_factory=list)

    def объясни(self) -> str:
        причины = []
        if self.чужие:
            причины.append("слова вне словаря: " + ", ".join(self.чужие))
        if self.непосильные:
            причины.append("формы не выводятся из пройденного: " + ", ".join(
                f"{ф} (№{н}, от {о})" for ф, н, о in self.непосильные))
        if self.нет_целевого:
            причины.append("нет целевого слова")
        return "; ".join(причины) or "годится"

    def оговорки(self) -> str:
        """Что прошло, но стоит знать. Пусто, если оговорок нет."""
        if not self.поздние:
            return ""
        return "формы со своим номером за пределом: " + ", ".join(
            f"{ф} (№{н})" for ф, н in self.поздние)


def слова_текста(текст: str) -> List[str]:
    return СЛОВО.findall(текст or "")


def ключ_повтора(текст: str, язык: str) -> str:
    """Чем два предложения считаются одним и тем же.

    Огласовки, регистр и знаки препинания к различию не относятся: человек
    узнаёт фразу, а не её запись.
    """
    слова = слова_текста(без_огласовок(текст))
    return " ".join(с if язык == "he" else с.lower() for с in слова)


def проверить(текст: str, целевое: str, словарь: Словарь) -> Итог:
    """Годится ли предложение для слова `целевое`."""
    найденные = слова_текста(текст)

    чужие, поздние, непосильные = [], [], []
    for с in найденные:
        путь, основа = словарь.опознать(с)
        if путь is None:
            # Повторы не копим: один и тот же огрех называется однажды.
            if с not in чужие:
                чужие.append(с)
            continue
        # Узнали — но, возможно, только морфологией. Если у самой формы есть
        # статья за пределом, решает путь: выводимую оговариваем, невыводимую
        # бракуем.
        if словарь.за_пределом(с):
            номер = словарь.свой_номер(с)
            if путь in словарь.ВЫВОДИМЫЕ:
                if (с, номер) not in поздние:
                    поздние.append((с, номер))
            elif (с, номер, основа) not in непосильные:
                непосильные.append((с, номер, основа))

    # Целевое слово ищем тем же узнаванием, что и остальные: в тексте оно
    # стоит в своей форме — с приставкой, во множественном числе, в прошедшем.
    цель = Словарь(язык=словарь.язык)
    цель.разрешено.add(без_огласовок(целевое) if словарь.язык == "he"
                       else без_огласовок(целевое).lower())
    есть_целевое = any(цель.знает(с) for с in найденные)

    return Итог(годится=not чужие and not непосильные and есть_целевое,
                чужие=чужие, нет_целевого=not есть_целевое,
                поздние=поздние, непосильные=непосильные)
