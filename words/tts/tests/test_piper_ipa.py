"""Голос Piper noa: наша транскрипция → запись, на которой учили модель.

Модель he_IL-noa-medium обучена на произношении из renikud: знак ударения
стоит прямо перед ударной гласной («ʃalˈom») и есть у каждого слова, даже
односложного. У нас — перед слогом («ʃaˈlom») и у односложных его нет.
Образцы 21.11.2026: по нашей транскрипции и по renikud владелец разницы не
услышал — значит, перевод верен, и берём нашу, где выверены омографы.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from piper_ipa import (в_запись_модели, обрезать_тишину, первый_вариант,  # noqa: E402
                       фраза_для_модели)


def test_ударение_переезжает_к_гласной():
    assert в_запись_модели("ʔaˈni") == "ʔanˈi"
    assert в_запись_модели("ʁoˈtse") == "ʁotsˈe"
    assert в_запись_модели("neheˈdaʁ") == "nehedˈaʁ"


def test_односложному_ставится_ударение():
    assert в_запись_модели("ʃel") == "ʃˈel"
    assert в_запись_модели("hi") == "hˈi"


def test_фраза_по_словам():
    assert в_запись_модели("ʔaˈni lo joˈdea") == "ʔanˈi lˈo jodˈea"


def test_из_словаря_берётся_первый_вариант_без_косых():
    assert первый_вариант("/ʔaˈni/") == "ʔaˈni"
    assert первый_вариант("/ˈjetseʁ/, /jaˈtsaʁ/") == "ˈjetseʁ"
    assert первый_вариант("") == ""


def test_тишина_по_краям_срезается_но_не_вплотную():
    sr = 1000
    звук = np.concatenate([np.zeros(500), np.full(300, 0.5), np.zeros(400)]).astype(np.float32)
    out = обрезать_тишину(звук, sr, запас_мс=40)
    assert len(out) == 300 + 2 * 40
    assert обрезать_тишину(np.zeros(100, dtype=np.float32), sr).size == 100   # тишину целиком не трогаем


def test_фраза_целиком_с_шестью_пробелами_и_без_знаков():
    """
    Владелец выбрал по образцам 21.11.2026 вариант O. По слову (B) —
    «интонации неестественные», знаки препинания между словами (E, G, K, L, M)
    — «каждое слово произносится отдельно», паузы, вставленные после синтеза
    (H, J), — «резкие прерывания», 12–24 пробела — «заменяются на эээ».
    Шесть пробелов: интонация фразы общая, стыки слов чуть длиннее.
    """
    assert фраза_для_модели("ʔaˈni ʁoˈtse") == "ʔanˈi" + " " * 6 + "ʁotsˈe"
    assert not any(ch in фраза_для_модели("ʔaˈni, lo joˈdea.") for ch in ",.;:")
