"""Подготовка к синтезу голосом Piper noa — без самого Piper.

Отдельно от piper_noa.py, чтобы проверяться в общем прогоне: Piper и его
разбор иврита живут в своём окружении на Python 3.12 (~/tools/piper-env),
а проверки проекта идут на 3.10.
"""
import numpy as np

ГЛАСНЫЕ = set("aeiouə")


def первый_вариант(ipa: str) -> str:
    """Транскрипция из словаря: первый вариант, без косых черт."""
    return (ipa or "").split(",")[0].strip().strip("/").strip()


def в_запись_модели(ipa: str) -> str:
    """Наша IPA → запись, на которой учили модель (renikud).

    Ударение — прямо перед ударной гласной, а не перед слогом, и у каждого
    слова, даже односложного: так модель и училась.
    """
    слова = []
    for с in ipa.split():
        if "ˈ" not in с:
            i = next((k for k, ch in enumerate(с) if ch in ГЛАСНЫЕ), None)
            с = с if i is None else с[:i] + "ˈ" + с[i:]
        else:
            out, ждём = [], False
            for ch in с:
                if ch == "ˈ":
                    ждём = True
                    continue
                if ждём and ch in ГЛАСНЫЕ:
                    out.append("ˈ")
                    ждём = False
                out.append(ch)
            с = "".join(out)
        слова.append(с)
    return " ".join(слова)


ПРОБЕЛОВ_МЕЖДУ_СЛОВАМИ = 6


def фраза_для_модели(ipa: str) -> str:
    """Предложение для синтеза целиком: без знаков препинания, слова через
    шесть пробелов.

    Владелец выбрал по образцам 21.11.2026 вариант O. По слову —
    «интонации неестественные»; знаки препинания между словами — «каждое
    слово произносится отдельно»; паузы, вставленные после синтеза, —
    «резкие прерывания»; 12–24 пробела модель заполняет протяжным «эээ».
    Пробел для неё — граница слова, а не конец фразы: интонация остаётся
    общей, а стыки слов чуть длиннее.
    """
    чистый = "".join(ch for ch in ipa if ch not in ",.;:!?")
    return (" " * ПРОБЕЛОВ_МЕЖДУ_СЛОВАМИ).join(в_запись_модели(чистый).split())


def обрезать_тишину(звук: np.ndarray, sr: int, порог: float = 0.01,
                    запас_мс: int = 40) -> np.ndarray:
    """Срезать тишину по краям, оставив запас — как обрезка у других голосов."""
    громко = np.flatnonzero(np.abs(звук) > порог)
    if громко.size == 0:
        return звук
    запас = int(sr * запас_мс / 1000)
    начало = max(0, громко[0] - запас)
    конец = min(len(звук), громко[-1] + 1 + запас)
    return звук[начало:конец]
