def test_у_каждого_слова_списка_есть_перевод(список, переводы):
    """
    Главный сторож итога. Слово в списке без перевода — это слово, которое
    человеку покажут пустым. Прежний словарь закрывает около трёх четвертей,
    остальное переведено вручную, и ни одной дырки остаться не должно.
    """
    без_перевода = [w for _, w, _, откуда in список
                    if откуда == "нужен" and w not in переводы]
    assert not без_перевода, (
        f"{len(без_перевода)} слов без перевода, например: {без_перевода[:15]}")


def test_отброшенные_слова_в_список_не_вернулись(список, отброшено):
    """
    Сторож против забывчивости сборщика. Отброшенное человеком слово обязано
    остаться за бортом при любой пересборке, иначе каждая из них возвращала бы
    имена и дубли-формы, и работа шла бы по кругу.
    """
    вернулись = [w for _, w, _, _ in список if w in отброшено]
    assert not вернулись, f"отброшенное вернулось в список: {вернулись[:15]}"


def test_слово_или_переведено_или_отброшено_но_не_оба(переводы, отброшено):
    оба = sorted(set(переводы) & set(отброшено))
    assert not оба, f"слово и переведено, и отброшено: {оба[:10]}"


def test_переводы_непустые_и_на_русском(переводы):
    """Пустой перевод и перевод латиницей — одинаково бесполезны человеку."""
    плохие = []
    for w, значение in переводы.items():
        if not isinstance(значение, list) or not значение:
            плохие.append((w, "не список или пуст"))
            continue
        if not all(isinstance(x, str) and x.strip() for x in значение):
            плохие.append((w, "пустая строка в переводе"))
            continue
        if not any(set(x.lower()) & set("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
                   for x in значение):
            плохие.append((w, f"нет кириллицы: {значение}"))
    assert not плохие, f"негодные переводы: {плохие[:10]}"


def test_у_каждого_отброшенного_есть_причина(отброшено):
    без_причины = [w for w, причина in отброшено.items()
                   if not isinstance(причина, str) or not причина.strip()]
    assert not без_причины, f"отброшено без причины: {без_причины[:10]}"


def test_переводов_столько_сколько_слов_требует_список(список, переводы):
    """
    Опора против лишнего: перевод слова, которого в списке нет, значит список
    пересобрали, а переводы остались от прежнего. Лишнее не ломает словарь, но
    говорит, что файлы разъехались.
    """
    в_списке = {w for _, w, _, _ in список}
    лишние = sorted(set(переводы) - в_списке)
    assert len(лишние) < 500, (
        f"{len(лишние)} переводов для слов вне списка — файлы разъехались: "
        f"{лишние[:10]}")
