"""Сторожи для учебного частотного списка английского.

Проверяется собранный список (data/eng_freq/frequency.txt), а не сборщик:
файла частот wordfreq в репозитории нет — он весит пятьдесят семь мегабайт и
нужен один раз. В репозиторий едет результат, значит и проверять надо его.

Главный сторож здесь — первый. Правило «слово короче трёх букв — сокращение»
срезало начало языка: «to», «a», «i», «in», «is», «it». На остатке, который
уходит в перевод, этого не видно вовсе: короткие слова все есть в прежнем
словаре и в остаток не попадают. Ошибка нашлась только на полном списке.
"""
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / "eng_tools"))

from filters import разметить  # noqa: E402

ДАННЫЕ = КОРЕНЬ / "data" / "eng_freq"


@pytest.fixture(scope="module")
def список():
    путь = ДАННЫЕ / "frequency.txt"
    if not путь.exists():
        pytest.skip("список ещё не собран")
    строки = [l.split("\t") for l in путь.read_text(encoding="utf-8").splitlines()
              if l and not l.startswith("#")]
    return [(int(r[0]), r[1], r[2], r[3]) for r in строки]


@pytest.fixture(scope="module")
def слова(список):
    return {w: ранг for ранг, w, _, _ in список}


# ── состав списка ───────────────────────────────────────────────────────────

def test_короткие_слова_не_приняты_за_сокращения(слова):
    """
    Сторож против срезанного начала языка. Эти слова — первая двадцатка любого
    частотного списка английского, и потерять их значит потерять язык.
    """
    пропущены = [w for w in ("to", "a", "i", "in", "is", "it", "of", "be", "on",
                             "as", "at", "an", "he", "we", "me", "my", "no", "do",
                             "so", "up", "us", "if", "by", "go")
                 if w not in слова]
    assert not пропущены, f"настоящие короткие слова выброшены: {пропущены}"


def test_первая_десятка_на_своих_местах(слова):
    """Опора: порядок именно частотный, а не алфавитный или случайный."""
    for w in ("the", "to", "and", "of", "a", "in"):
        assert слова[w] <= 10, f"«{w}» на {слова[w]}-м месте — порядок не частотный"


def test_бытовые_слова_которых_не_было_в_прежнем_словаре(слова):
    """
    Причина всей работы. Прежний словарь деловой: в нём нет ни кота, ни смеха,
    ни голода. Новый список обязан их содержать, иначе менять было нечего.
    """
    пропущены = [w for w in ("cat", "laugh", "hungry", "flower", "soup", "spoon",
                             "kiss", "hug", "towel", "pillow", "onion", "garlic")
                 if w not in слова]
    assert not пропущены, f"бытовые слова не попали в список: {пропущены}"


def test_ровно_столько_слов_сколько_заказано(список):
    assert len(список) == 10000
    assert [r for r, *_ in список] == list(range(1, 10001)), "ранги с пропусками"


def test_слов_без_повторов(список):
    из_списка = [w for _, w, _, _ in список]
    повторы = {w for w in из_списка if из_списка.count(w) > 1} if len(
        set(из_списка)) != len(из_списка) else set()
    assert not повторы, f"слова повторяются: {sorted(повторы)[:10]}"


def test_прежний_словарь_закрывает_большую_часть(список):
    """
    Опора под решением не переводить всё заново. Если доля упадёт, значит
    список собран из другого корпуса и расчёт работы надо пересматривать.
    """
    старых = sum(1 for *_, откуда in список if откуда == "старый")
    assert старых / len(список) > 0.6, f"из прежнего словаря всего {старых}"


