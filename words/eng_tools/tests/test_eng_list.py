def test_отсеянное_записано_с_причиной():
    путь = ДАННЫЕ / "rejected.json"
    if not путь.exists():
        pytest.skip("отсев ещё не записан")
    d = json.loads(путь.read_text(encoding="utf-8"))
    # Четвёртая причина появляется после первой же пересборки: слова, которые
    # человек выбросил на переводе, сборщик обязан помнить и не брать снова.
    assert set(d) <= {"мат", "сокращение", "название", "отброшено вручную"}
    assert "fuck" in d["мат"] and "lol" in d["сокращение"]
    assert "facebook" in d["название"]


# ── разметка имён ───────────────────────────────────────────────────────────

def test_слова_которые_заодно_имена_остаются_словами():
    """
    Половина английских имён это обычные слова. Отсев по списку имён без этой
    поправки забрал бы «благодать», «розу», «надежду» и «метку».
    """
    имена = {"grace", "rose", "mark", "will", "faith", "hope", "earl", "pearl",
             "angel", "may", "june", "art", "ruby", "violet", "olive"}
    for w in sorted(имена):
        assert разметить(w, имена) == "слово", f"«{w}» выброшено как имя"


def test_настоящее_имя_помечается_а_не_выбрасывается():
    """Помечается, не отсеивается: решение за человеком."""
    assert разметить("jason", {"jason"}) == "возможно имя"
    assert разметить("hannah", {"hannah"}) == "возможно имя"


def test_помеченные_имена_в_списке_остались(список):
    """Опора: пометка не превратилась в тихий отсев."""
    помечено = [w for _, w, вид, _ in список if вид == "возможно имя"]
    assert помечено, "ни одного помеченного слова — разметка не работает"
    assert len(помечено) < len(список) * 0.1, "слишком много помечено именами"


