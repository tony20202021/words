"""Сторожи готового словаря английского (data/eng_freq/eng10k.json).

Формат тот же, что у прежнего data/eng.json, потому что его читает уже
написанная оснастка — загрузка в базу и сбор транскрипций. Проверяется именно
то, что оснастка от словаря ждёт, и то, на чём он однажды сломался.

Сторож про пустой перевод здесь главный. В прежнем словаре пятнадцать записей
с пустым description — «am», «ones», «Its», «THE». Сборщик списка проверял,
есть ли слово в прежнем словаре, а не есть ли у него перевод, и три таких
слова попали в итог пустыми: в приложении человек увидел бы слово без перевода
и ничего бы не понял.
"""
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / "eng_tools"))

ДАННЫЕ = КОРЕНЬ / "data" / "eng_freq"
СЛОВАРЬ = ДАННЫЕ / "eng10k.json"


@pytest.fixture(scope="module")
def словарь():
    if not СЛОВАРЬ.exists():
        pytest.skip("словарь ещё не собран")
    return json.loads(СЛОВАРЬ.read_text(encoding="utf-8"))


def test_в_словаре_ровно_десять_тысяч_записей(словарь):
    assert len(словарь) == 10000
    assert sorted(int(k) for k in словарь) == list(range(1, 10001)), "номера с пропусками"


def test_ни_одной_записи_без_перевода(словарь):
    """
    Главный сторож. Слово без перевода бесполезно и молчит о своей беде:
    в приложении оно выглядит обычным, пока человек не откроет его.
    """
    пустые = [r["word"] for r in словарь.values() if not (r.get("description") or [])]
    assert not пустые, f"{len(пустые)} записей без перевода: {пустые[:15]}"


def test_каждая_запись_несёт_поля_которых_ждёт_оснастка(словарь):
    обязательные = {"word", "transcription", "description", "frequency",
                    "language", "all_transcriptions"}
    for ключ, r in list(словарь.items())[:200]:
        не_хватает = обязательные - set(r)
        assert not не_хватает, f"запись {ключ} без полей {не_хватает}"
        assert r["language"] == "en"
        assert isinstance(r["description"], list)
        assert isinstance(r["all_transcriptions"], list)


def test_номер_записи_совпадает_с_частотой(словарь):
    """Опора: ключ и поле frequency — одно и то же, иначе порядок разъедется."""
    расхождения = [k for k, r in словарь.items() if int(k) != r["frequency"]]
    assert not расхождения, f"ключ не равен frequency: {расхождения[:10]}"


def test_слова_не_повторяются(словарь):
    слова = [r["word"] for r in словарь.values()]
    assert len(set(слова)) == len(слова), "слово встречается дважды"


def test_переводы_на_русском(словарь):
    КИРИЛЛИЦА = set("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
    плохие = [r["word"] for r in словарь.values()
              if not any(set(x.lower()) & КИРИЛЛИЦА for x in r["description"])]
    assert not плохие, f"перевод без кириллицы: {плохие[:10]}"


def test_у_слов_из_прежнего_словаря_транскрипция_сохранилась(словарь):
    """
    Опора: транскрипции прежнего словаря — главная ценность, которую мы
    унаследовали. Если их растерять, собирать заново придётся семь тысяч штук.
    """
    с_транскрипцией = sum(1 for r in словарь.values() if r["transcription"])
    assert с_транскрипцией > 6000, (
        f"транскрипций всего {с_транскрипцией} — прежние потеряны")


# ── транскрипции ────────────────────────────────────────────────────────────

def test_транскрипция_есть_почти_у_всех(словарь):
    """
    Транскрипция собирается из открытого словаря ipa-dict, и он закрывает
    99,9% списка. Если доля упадёт, значит словарь не подключили или список
    собран из другого корпуса — и человек останется без подсказки, как слово
    читается.
    """
    с_транскрипцией = [r for r in словарь.values() if r["transcription"]]
    доля = len(с_транскрипцией) / len(словарь)
    assert доля > 0.99, (
        f"транскрипция лишь у {len(с_транскрипцией)} слов ({100*доля:.1f}%)")


def test_богатые_транскрипции_прежнего_словаря_не_обеднели(словарь):
    """
    Сторож против замены вместо слияния. Оснастка word_transcription/
    переписывает поле целиком, и прогон по локальному словарю обеднил 5658
    записей: прежний словарь собирал из двух источников, и Викисловарь
    добавлял варианты — чаще британские. Здесь закреплены те самые слова,
    на которых потеря видна глазом.
    """
    ожидаемое = {
        "the": "/ˈðiː/",      # британский вариант от Викисловаря
        "to": "/tuː/",
        "for": "/fɔː(ɹ)/",
        "you": "/juː/",
        "of": "/ɒv/",
    }
    по_слову = {r["word"]: r["transcription"] for r in словарь.values()}
    потеряно = [w for w, вариант in ожидаемое.items()
                if вариант not in (по_слову.get(w) or "")]
    assert not потеряно, (
        f"из транскрипций пропали британские варианты: "
        f"{[(w, по_слову.get(w)) for w in потеряно]}")


def test_у_каждой_транскрипции_назван_источник(словарь):
    """Транскрипция без источника — выдуманная, а выдумывать их нельзя."""
    безымянные = [r["word"] for r in словарь.values()
                  if r["transcription"] and not r["all_transcriptions"]]
    assert not безымянные, f"транскрипция без источника: {безымянные[:10]}"
